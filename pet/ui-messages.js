export const ui = (key, params = {}) => ({key, params})
export const uiLanguage = locale => /^zh(?:-|$)/i.test(String(locale ?? 'zh')) ? 'zh' : 'en'
export function renderUi(descriptor, locale = 'zh') {
  if (!descriptor || !Object.hasOwn(UI_MESSAGES.zh, descriptor.key)) return undefined
  const template = UI_MESSAGES[uiLanguage(locale)][descriptor.key]
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const value = descriptor.params?.[key]
    return value == null ? match : typeof value === 'object' && value.key ? renderUi(value, locale) ?? value.key : String(value)
  })
}
export const zhUi = descriptor => renderUi(descriptor, 'zh')
export function uiError(key, params) {
  const descriptor = ui(key, params), error = new Error(zhUi(descriptor))
  error.ui = descriptor
  return error
}
export function projectUiState(state, locale = 'zh') {
  if (!state) return state
  const lines = item => (item?.lines ?? []).map((line, i) => renderUi(item.linesUi?.[i], locale) ?? line)
  const result = {...state, uiLocale:uiLanguage(locale), nativeUi:Object.fromEntries(["windowTitle", "showPet", "hidePet", "showBubble", "hideBubble", "close", "waiting", "progressUnit"].map(key=>[key,renderUi(ui("native.ui."+key),locale)]))}
  if (state.task) result.task = {...state.task, text:renderUi(state.task.ui, locale) ?? state.task.text, tool:renderUi(state.task.toolUi, locale) ?? state.task.tool}
  if (state.stats) result.stats = {...state.stats, lines:lines(state.stats)}
  if (state.usage) {
    result.usage = {...state.usage, title:renderUi(state.usage.titleUi, locale) ?? state.usage.title, lines:lines(state.usage), details:(state.usage.details??state.usage.lines??[]).map((line,i)=>renderUi(state.usage.detailsUi?.[i]??state.usage.linesUi?.[i],locale)??line), windows:(state.usage.windows ?? []).map(w=>({...w,label:renderUi(w.labelUi,locale) ?? w.label}))}
    if (state.usage.kind === 'balance' && state.usage.balances && uiLanguage(locale) === 'en') {
      result.usage.lines = result.usage.lines.map((line, i) => {
        const r = state.usage.balances[i]
        return r ? `${r.currency==='CNY'?'¥':r.currency==='USD'?'$':r.currency+' '}${Number(r.total).toLocaleString('en-US',{maximumFractionDigits:4})}` : line
      })
    }
  }
  result.nativeError = renderUi(state.nativeErrorUi, locale) ?? state.nativeError
  return result
}
